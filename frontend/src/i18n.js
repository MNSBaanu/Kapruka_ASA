export function formatMoney(amount, currency = 'LKR') {
  if (typeof amount !== 'number') return ''
  return `${currency} ${amount.toLocaleString('en-LK', { maximumFractionDigits: currency === 'LKR' ? 0 : 2 })}`
}

export function formatDate(iso, lang = 'en') {
  if (!iso) return ''
  const date = new Date(`${iso}T00:00:00`)
  if (Number.isNaN(date.getTime())) return iso
  return date.toLocaleDateString(lang === 'en' ? 'en-GB' : lang, { weekday: 'short', day: 'numeric', month: 'short' })
}
